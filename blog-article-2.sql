Most UK taxi and private hire drivers pay somewhere between £1,200 and £3,000 a year for insurance, and hackney carriage drivers often pay £2,000 to £5,000. A typical figure for 2026 is around £1,900 to £2,500 a year.

That's a big range, and where you land in it comes down to a handful of things you can control and a few you can't. Here's what drivers are actually paying, what pushes the price up, and how to bring it down without cutting corners.

## Why taxi insurance costs so much more than normal car insurance

Your normal car insurance doesn't cover you to carry paying passengers. For that you need hire and reward cover, and insurers see it as much higher risk:

- you're on the road for far more hours and miles than a normal driver
- you drive at night, in city centres and at closing time
- you carry strangers, so a crash can mean several injury claims at once
- your car is your income, so claims and repairs cost more

Your council or TfL won't license you or your vehicle without the right cover, so this isn't a bill you can skip.

## What drivers are paying in 2026

These are typical yearly figures from UK insurers and comparison sites. Your own quote could be higher or lower.

- App-based private hire (Uber, Bolt and similar): about £1,200 to £2,500
- Private hire working for a local operator: about £1,500 to £3,000
- Hackney carriage (public hire): about £2,000 to £5,000 or more
- Chauffeur and executive: about £1,800 to £3,500

To give you a real-world marker, Zego says even its cheapest 10% of Uber drivers on annual cover paid around £2,000 or less.

If you pay monthly, expect roughly £100 to £420 a month depending on your type of work.

## What pushes your price up

### Where you work

London is the most expensive place in the UK to insure a taxi, followed by big cities like Birmingham and Manchester. More traffic means more crashes, and more crime means more theft and damage claims. A driver in a quiet market town will usually pay far less than one working central London.

### Hackney or private hire

Public hire costs more than private hire. Hackney drivers work ranks, pick up from the street and usually cover more miles. Purpose-built cabs like the LEVC TX and wheelchair-accessible vehicles also cost more to repair, and that shows in the premium.

### Your age and experience

Under-25s pay the most. Drivers with less than two years of taxi or private hire experience also pay a lot more, and newly licensed hackney drivers in city centres can be quoted over £4,000. The price drops as you build up a clean record.

### Claims and points

A fault claim in the last five years can add 20% to 50% to your premium. Some points hurt more than others. A speeding conviction might add 5% to 25%, but a mobile phone offence (CU80) can add 30% to 60%. One moment on the phone could cost you more than a year of fuel savings.

### Your car

Insurers look at the make, model, value and insurance group of your car. A newer, pricier car or one that's expensive to repair costs more to cover.

### Your level of cover

- Third party only: covers damage to other people and their property, not your own car. Cheapest, but you're on your own if your car is written off.
- Third party, fire and theft: adds cover if your car is stolen or catches fire.
- Fully comprehensive: also covers damage to your own car. Costs more, but if your car is your living, losing it without a payout can finish you.

Don't assume third party is always cheapest. It sometimes isn't, so get prices for all three.

## How to bring your insurance cost down

### 1. Shop around every year

Never just let it auto-renew. Get quotes from a few insurers or a specialist taxi broker a few weeks before renewal. You can get quotes from our insurance partners on the [UK Driver Hub insurance page](/insurance). One form, and a specialist calls you back.

### 2. Pay annually if you can

Paying monthly is basically a loan. It usually costs 10% to 15% more overall, and some monthly plans charge over 30% APR. If you can save up for the annual payment, you'll keep that money.

### 3. Protect your no-claims bonus

Five years claim-free can knock 60% or more off your premium. Protecting your no-claims bonus costs a bit extra but can be worth it when you've built a lot up.

### 4. Think about telematics

A black box or app records how you drive. If you drive smoothly, it can bring your price down at renewal. It's especially worth a look if you're young or newly licensed.

### 5. Raise your voluntary excess, carefully

Moving your excess from £250 to £500 can trim around 8% to 15% off the price. Only do it if you could actually pay that £500 the day you need to claim.

### 6. Fit a dash cam

A dash cam won't always cut your premium, but some insurers give a discount. More importantly, it proves what happened when someone pulls out on you or claims you hit them. Non-fault claims settled fast protect your record.

### 7. Look at pay-as-you-go cover if you're part-time

If you only drive a few days a week or a few months a year, hourly or 30-day policies can work out cheaper. Once you're driving most of the year, an annual policy is usually better value.

### 8. Be honest on the form

Never leave out points, claims or mods, and never put the policy in someone else's name ("fronting"). If the insurer finds out after a crash, they can refuse to pay and cancel your policy, and you could be left paying for everything yourself. In serious cases it's treated as insurance fraud.

## Renting your car? Check what's included

Many drivers rent from a fleet or PCO rental company, and the weekly rent often includes insurance. Before you sign:

- check exactly what the insurance covers and what the excess is (it can be £1,000 or more)
- ask whether you're covered for the work you do, such as Uber, local operators or airport runs
- get it in writing

A cheap weekly rent with a £2,000 excess can turn out to be very expensive after one bump.

## Don't forget public liability insurance

Hire and reward cover protects you on the road. Public liability covers you if a passenger gets hurt in another way, like slipping getting out of your car or catching their hand in the door. Many councils ask for it, especially for hackney drivers, and it usually costs about £50 to £150 a year. Some taxi policies already include it, so check before you buy it twice.

## Can I claim insurance against tax?

Yes, if you work out your tax using actual costs. Your hire and reward insurance is an allowable expense, along with fuel, repairs, licence fees and so on.

If you use simplified expenses (the mileage rate) instead, you can't claim insurance separately, because the mileage rate already covers it.

Either way, keep your insurance documents and receipts. You can log your insurance and every other cost in the free [UK Driver Hub Earnings and Expenses tracker](/finance), so everything's ready when your tax return or Making Tax Digital update is due.

## The bottom line

Insurance is one of your biggest costs, after fuel and your car. Most drivers pay between £1,200 and £3,000 a year, hackney drivers often more, and the drivers who pay least are the ones with clean records who shop around every year.

Keep your record clean, put the phone down, pay annually if you can, and never let your policy auto-renew without checking the market first.

