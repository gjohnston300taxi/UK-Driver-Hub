To drive a taxi or private hire car in the UK, you need a driver's licence from your local council, or from TfL if you want to work in London. That means an enhanced DBS check, a Group 2 medical, a local knowledge test and some paperwork for HMRC.

Budget roughly £500 to £800 for the licence, checks, tests and medical before you even think about a car or insurance. Allow anything from a few weeks to a few months, depending on your council.

Here's the whole process, step by step, from drivers who've been through it.

## First: taxi or private hire?

Before you fill in a single form, decide which badge you're going for. They are different licences with different rules.

- Hackney carriage (taxi): you can work the ranks and be flagged down in the street within your licensing area, and fares are set by the council meter.
- Private hire (minicab, Uber, Bolt): every job must be pre-booked through a licensed operator. You cannot pick up off the street or use ranks.

Picking up a private hire fare that hasn't been booked is plying for hire. It can cost you your licence, and your insurance won't cover the journey.

In England and Wales, a private hire driver, their car and their operator all need licences from the same council. Bear that in mind if you plan to work for a firm in a neighbouring town.

## What you need before you apply

Every council sets its own policy, but most ask for the same basics:

- Age: usually at least 21. TfL asks for 21, but some councils accept 18.
- A full UK driving licence, held for at least one to three years. TfL asks for three years, and some councils, such as Aberdeen, ask for 12 months.
- The right to live and work in the UK.
- An enhanced DBS check, and in most areas a subscription to the DBS Update Service.
- A Group 2 medical, the same standard used for bus and lorry drivers.
- A record your council is happy with. Councils follow national guidance on convictions, so serious, recent or dishonesty-related offences can count against you.

Download your council's taxi and private hire policy first. It lists exactly what it wants, and it will save you a wasted trip.

## Step by step: how to get your licence

### 1. Contact your council and get the application pack

Search for your council's name followed by "taxi licensing". Most now let you apply online. Read the policy, check the fees, and note any tests you need to book.

### 2. Apply for your enhanced DBS check

Your council will tell you how to apply. Many use their own provider. From 5 October 2026 the government fee for an enhanced DBS check dropped to £41, although councils and providers often add a small admin charge on top.

Sign up to the DBS Update Service as soon as your certificate arrives. It costs £15 a year from October 2026. Councils are expected to check your DBS status every six months, and the Update Service lets them do it online instead of you paying for a fresh check each time.

### 3. Book your Group 2 medical

Your GP or another doctor who can see your full medical history fills in the medical form. Doctors set their own fee, so ring round before you book.

The medical looks at things like eyesight, diabetes, heart conditions and anything that could affect your driving. If you have a condition, don't panic: many drivers with well-managed conditions still pass. Just be honest on the form.

### 4. Pass your tests and training

This part varies the most between councils. Expect some or all of these:

- A local knowledge or topographical test covering routes, streets and landmarks.
- An English speaking and listening test, in some areas including London.
- Safeguarding training, so you can spot and report signs of exploitation.
- Disability awareness training, or a recognised qualification such as a BTEC in some areas.

Hackney carriage knowledge tests are usually harder than private hire tests, because you need to know the area without a satnav.

### 5. Sort your HMRC tax check

If this is your first ever taxi or private hire licence, you just confirm on the form that you know what tax you need to pay as a self-employed driver.

When you renew, or if you've held a licence in the last 12 months, you need to complete an HMRC tax check online first. You get a 9-character code to give to your council. The code lasts 120 days, so don't do it too early. Search GOV.UK for "tax check for a taxi licence" to find it.

### 6. Submit your application and pay the fees

Send in everything together: application form, photo, DBS details, medical, test results, tax confirmation and proof of your right to work. An incomplete application is the number one reason for delays, so check it twice.

### 7. Get a licensed vehicle and the right insurance

Your car also needs a vehicle licence. It has to pass the council's inspection and meet its age and emissions rules. Plenty of new private hire drivers rent a car that's already licensed while they find their feet.

You'll need taxi or private hire insurance, often called "hire and reward" cover. Normal car insurance does not cover you to carry paying passengers.

### 8. Register as self-employed

Most drivers are self-employed. Register with HMRC for Self Assessment by 5 October after the end of the tax year you started driving. Keep every receipt from day one: fuel, insurance, licence fees, app commission and cleaning can all reduce your tax bill.

If your takings are over £50,000 a year, you also need to follow Making Tax Digital rules. That threshold drops to £30,000 from April 2027.

## Becoming a private hire driver in London (PCO)

London is licensed by TfL, often still called the PCO. TfL currently asks for:

- Age 21 or over, and a full driving licence held for at least three years.
- An enhanced DBS check through TfL's provider, plus the DBS Update Service.
- A Group 2 medical.
- A Certificate of Good Conduct for any country you lived in for three months or more in the last 10 years.
- An online safeguarding awareness course.
- A topographical skills assessment, a speaking and listening assessment, and the SERU assessment on rules and safety.

TfL's own example adds up to about £477 before the medical. That includes a £124 application fee, £186 for the licence itself, the DBS check, and £36 for each assessment. Check TfL's website for current fees before you apply.

TfL has had long waiting times in the past, so get your application in early and make sure it's complete.

## Scotland and Northern Ireland

In Scotland, councils license taxis and private hire cars under Scottish law. The steps are similar: a criminal record check, a medical, a local knowledge test and a tax check. Some councils, such as Aberdeen, grant a first licence for one year and renewals for up to three years.

In Northern Ireland, taxi licences are issued by the Driver and Vehicle Agency (DVA) rather than councils.

## How much does it cost?

Fees vary a lot between councils, but as a rough guide:

- Driver licence fee: from about £150 to over £300, for up to three years.
- Enhanced DBS: £41 government fee plus any admin charge.
- DBS Update Service: £15 a year.
- Group 2 medical: set by your doctor.
- Knowledge and other tests: often £30 to £50 each.
- Training courses: these vary, so check your council's policy.

On top of that comes your car, whether you buy, finance or rent, and your insurance. Those are your biggest costs by far.

## Mistakes that slow drivers down

- Sending in an application with something missing.
- Forgetting to join the DBS Update Service in time.
- Getting your medical done by a doctor who can't see your medical history.
- Doing your tax check too early, so the 120-day code runs out.
- Starting work before your licence and insurance are both in place.

